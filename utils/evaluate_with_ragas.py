def save_checkpoint(
    output_dir: Path,
    results_so_far: list[dict],
    records_evaluated: int,
    total_records: int,
    tracker: "TokenTracker",
    metadata: dict,
):
    """Saves an intermediate checkpoint."""
    output_dir.mkdir(parents=True, exist_ok=True)
    ckpt = {
        "timestamp": datetime.now().isoformat(),
        "records_evaluated": records_evaluated,
        "total_records": total_records,
        "token_usage": tracker.summary(),
        "metadata": metadata,
        "results": results_so_far,
    }
    ckpt_path = output_dir / "checkpoint.json"
    with open(ckpt_path, "w", encoding="utf-8") as f:
        json.dump(ckpt, f, indent=2, ensure_ascii=False, default=str)
    return ckpt_path


def load_checkpoint(ckpt_path: Path) -> dict:
    """Loads a previous checkpoint."""
    with open(ckpt_path, "r", encoding="utf-8") as f:
        return json.load(f)


# ══════════════════════════════════════════════════════════════════════════════
#  EVALUATION — record by record (con checkpoint)
