# API keys dal .env (supporta rotazione)
def _load_api_keys() -> list[str]:
    """Loads all available API keys from .env."""
    keys = []
    # API key principale
    main_key = os.getenv("GEMINI_API_KEY", "")
    if main_key:
        keys.append(main_key)
    # API key aggiuntive (API_KEY_1, API_KEY_2, ...)
    for i in range(1, 10):
        k = os.getenv(f"API_KEY_{i}", "")
        if k and k not in keys:
            keys.append(k)
    return keys


