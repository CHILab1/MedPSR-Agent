def load_dataset(dataset_path: Path) -> list[dict]:
    """Loads RAGAS dataset from JSON file."""
    with open(dataset_path, "r", encoding="utf-8") as f:
        records = json.load(f)
    console.print(f"[green][OK] Dataset loaded: {len(records)} records from {dataset_path.name}[/green]")
    return records


def filter_valid_records(records: list[dict]) -> list[dict]:
    """Filters valid records (with non-empty response and contexts)."""
    valid = []
    for rec in records:
        response = rec.get("response", "").strip()
        contexts = rec.get("retrieved_contexts", [])
        user_input = rec.get("user_input", "").strip()
        if response and contexts and user_input:
            valid.append(rec)
    skipped = len(records) - len(valid)
    if skipped:
        console.print(f"  [yellow][WARN] {skipped} records skipped (missing data)[/yellow]")
    console.print(f"  Valid: {len(valid)}/{len(records)}")
    return valid


def build_ragas_dataset(records: list[dict]) -> "EvaluationDataset":
    """Builds RAGAS EvaluationDataset from records."""
    samples = []
    for rec in records:
        sample = SingleTurnSample(
            user_input=rec["user_input"],
            response=rec["response"],
            retrieved_contexts=rec["retrieved_contexts"],
            reference=rec.get("reference"),
        )
        samples.append(sample)
    return EvaluationDataset(samples=samples)


def estimate_dataset_tokens(records: list[dict]) -> dict:
    """Estimates dataset tokens for cost preview."""
    total_chars = 0
    for rec in records:
        total_chars += len(rec.get("user_input", ""))
        total_chars += len(rec.get("response", ""))
        total_chars += sum(len(c) for c in rec.get("retrieved_contexts", []))
    est_tokens = total_chars // 4  # ~4 chars/token
    return {
        "total_chars": total_chars,
        "estimated_raw_tokens": est_tokens,
        "estimated_eval_tokens": est_tokens * 5,  # ~5x per le chiamate RAGAS
    }


# ══════════════════════════════════════════════════════════════════════════════
