def evaluate_single_record(
    record: dict,
    metrics: list,
    run_config: "RunConfig",
) -> dict:
    """Evaluates a single record with all RAGAS metrics."""
    sample = SingleTurnSample(
        user_input=record["user_input"],
        response=record["response"],
        retrieved_contexts=record["retrieved_contexts"],
        reference=record.get("reference"),
    )
    dataset = EvaluationDataset(samples=[sample])

    result = evaluate(
        dataset=dataset,
        metrics=metrics,
        run_config=run_config,
    )

    # Estrai i punteggi
    df = result.to_pandas()
    scores = {}
    for col in df.columns:
        if col not in ["user_input", "response", "retrieved_contexts", "reference"]:
            val = df[col].iloc[0]
            scores[col] = float(val) if val is not None else None
    return scores


def run_evaluation(
    dataset_path: Path,
    metric_names: list[str] = None,
    judge_model: str = "gemini-3.1-pro-preview",
    max_records: int = None,
    output_dir: Path = None,
    checkpoint_every: int = 5,
    resume_from: int = 0,
    existing_results: list[dict] = None,
):
    """
    Executes record-by-record RAGAS evaluation with checkpoints.

    Args:
        dataset_path:     Path to dataset JSON file
        metric_names:     List of metrics to compute
        judge_model:      Gemini model for judge
        max_records:      Limit number of records
        output_dir:       Directory output
        checkpoint_every: Save checkpoint every N records
        resume_from:      Index to resume from (for resume)
        existing_results: Already computed results (for resume)
    """
    if not RAGAS_AVAILABLE:
        console.print("[bold red][ERROR] RAGAS not installed! pip install ragas[/bold red]")
        sys.exit(1)

    metric_names = metric_names or ["clinical_comprehensiveness", "clinical_validity", "contradiction_rate", "answer_relevancy", "context_precision"]
    api_keys = _load_api_keys()
    use_vertex = os.getenv("USE_VERTEXAI", "false").lower() in ("true", "1", "yes")

    if not api_keys and not use_vertex:
        console.print("[bold red][ERROR] No API keys configured and USE_VERTEXAI not enabled![/bold red]")
        sys.exit(1)

    # ── Output directory ──
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_dir = output_dir or (_PROJECT_ROOT / "results" / f"ragas_eval_{timestamp}")
    output_dir.mkdir(parents=True, exist_ok=True)

    # ── Header ──
    console.rule("[bold cyan]RAGAS Evaluation - Clinical Agentic Pipeline[/bold cyan]")
    console.print(f"  Dataset:       {dataset_path.name}")
    console.print(f"  Judge Model:   {judge_model}")
    console.print(f"  Platform:      {'Vertex AI' if use_vertex else 'Google AI Studio'}")
    if not use_vertex:
        console.print(f"  API Keys:      {len(api_keys)} available")
    console.print(f"  Metrics:      {metric_names}")
    console.print(f"  Output:        {output_dir}")
    console.print()

    # ── Carica dataset ──
    records = load_dataset(dataset_path)
    records = filter_valid_records(records)

    if max_records and len(records) > max_records:
        records = records[:max_records]
        console.print(f"  [yellow][WARN] Limited to {max_records} records[/yellow]")

    if not records:
        console.print("[bold red]No valid records![/bold red]")
        sys.exit(1)

    # ── Stima costi ──
    est = estimate_dataset_tokens(records)
    console.print(f"\n  Estimated tokens (raw):     {est['estimated_raw_tokens']:,}")
    console.print(f"  Estimated tokens (eval):    {est['estimated_eval_tokens']:,}")
    console.print()

    # ── Setup LLM & Embeddings ──
    tracker = TokenTracker()
    ragas_llm = GeminiLLM(
        model=judge_model,
        api_keys=api_keys if not use_vertex else None,
        max_retries=5,
        base_delay=5.0,
        tracker=tracker,
    )
    ragas_embeddings = GeminiEmbeddings(
        model="gemini-embedding-001",
        api_key=api_keys[0] if (api_keys and not use_vertex) else None,
        tracker=tracker,
    )

    # ── Setup metriche ──
    all_metrics = {
        "clinical_comprehensiveness": ClinicalComprehensiveness(llm=ragas_llm),
        "clinical_validity": ClinicalValidity(llm=ragas_llm),
        "contradiction_rate": ContradictionRate(llm=ragas_llm),
        "answer_relevancy": AnswerRelevancy(llm=ragas_llm, embeddings=ragas_embeddings),
        "context_precision": LLMContextPrecisionWithoutReference(llm=ragas_llm),
    }
    metrics = []
    metric_name_mapping = {}
    for name in metric_names:
        if name in all_metrics:
            m_obj = all_metrics[name]
            metrics.append(m_obj)
            metric_name_mapping[name] = m_obj.name
            console.print(f"  [cyan][OK] Metric: {name}[/cyan]")
        else:
            console.print(f"  [yellow][WARN] Unknown metric: {name}[/yellow]")

    if not metrics:
        console.print("[bold red]No valid metrics![/bold red]")
        sys.exit(1)

    # ── RunConfig ──
    run_config = RunConfig(max_workers=2, timeout=900)

    # ── Risultati ──
    all_results = existing_results or []
    errors = []
    start_time = time.time()

    meta = {
        "dataset_path": str(dataset_path),
        "judge_model": judge_model,
        "metrics": metric_names,
        "n_records": len(records),
        "api_keys_count": len(api_keys),
    }

    # ── Loop principale ──
    console.rule("[bold green]STARTING EVALUATION[/bold green]")
    total = len(records)

    for i in range(resume_from, total):
        rec = records[i]
        rec_meta = rec.get("metadata", {})
        hadm_id = rec_meta.get("hadm_id", "?")
        q_id = rec_meta.get("question_id", "?")

        console.print(
            f"\n  [{i + 1}/{total}] hadm={hadm_id} | {q_id} | "
            f"tok={tracker.total_tokens:,}"
        )

        try:
            t0 = time.perf_counter()
            scores = evaluate_single_record(rec, metrics, run_config)
            elapsed = time.perf_counter() - t0

            result_entry = {
                "index": i,
                "hadm_id": hadm_id,
                "question_id": q_id,
                "question_category": rec_meta.get("question_category", ""),
                "user_input": rec["user_input"],
                **scores,
                "eval_time_seconds": round(elapsed, 1),
            }
            all_results.append(result_entry)

            # Print scores
            scores_str = " | ".join(f"{k}: {v:.3f}" if v is not None else f"{k}: N/A"
                                     for k, v in scores.items())
            console.print(f"    [green][OK][/green] {scores_str} ({elapsed:.1f}s)")

        except Exception as e:
            console.print(f"    [red][ERROR] {e}[/red]")
            errors.append({
                "index": i,
                "hadm_id": hadm_id,
                "question_id": q_id,
                "error": str(e),
                "traceback": traceback.format_exc(),
            })
            # Salva un risultato con NaN per non perdere il posto
            all_results.append({
                "index": i,
                "hadm_id": hadm_id,
                "question_id": q_id,
                "question_category": rec_meta.get("question_category", ""),
                "user_input": rec["user_input"],
                "error": str(e),
            })

        # ── Checkpoint ──
        if (i + 1) % checkpoint_every == 0 or i == total - 1:
            ckpt_path = save_checkpoint(
                output_dir, all_results, i + 1, total, tracker, meta,
            )
            console.print(
                f"    [yellow]Checkpoint {i + 1}/{total} saved | "
                f"Tokens: {tracker.total_tokens:,}[/yellow]"
            )

    # ── Tempo totale ──
    total_time = time.time() - start_time

    # ══════════════════════════════════════════════════════════════════════
    #  SALVATAGGIO FINALE
    # ══════════════════════════════════════════════════════════════════════

    console.rule("[bold green]SAVING RESULTS[/bold green]")

    # CSV risultati
    import pandas as pd
    results_df = pd.DataFrame(all_results)
    csv_path = output_dir / "ragas_results.csv"
    results_df.to_csv(csv_path, index=False, encoding="utf-8-sig")
    console.print(f"  CSV: {csv_path}")

    # JSON risultati completo
    json_path = output_dir / "ragas_results.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(all_results, f, indent=2, ensure_ascii=False, default=str)
    console.print(f"  JSON: {json_path}")

    # ── Summary con statistiche ──
    metric_cols = [c for c in results_df.columns
                   if c not in ["index", "hadm_id", "question_id", "question_category",
                                "user_input", "eval_time_seconds", "error"]]
    summary = {
        "evaluation_timestamp": datetime.now().isoformat(),
        "total_time_seconds": round(total_time, 1),
        "total_time_minutes": round(total_time / 60, 1),
        "n_records_total": total,
        "n_records_success": len([r for r in all_results if "error" not in r]),
        "n_records_error": len(errors),
        "judge_model": judge_model,
        "metrics_computed": metric_names,
        "token_usage": tracker.summary(),
        "cost_estimate": tracker.cost_estimate(judge_model),
        "metrics_summary": {},
        "metrics_by_category": {},
        "errors": errors,
    }

    # Metriche globali
    for col in metric_cols:
        if col in results_df.columns and results_df[col].dtype in ["float64", "float32"]:
            valid_vals = results_df[col].dropna()
            if len(valid_vals) > 0:
                summary["metrics_summary"][col] = {
                    "mean": round(float(valid_vals.mean()), 4),
                    "std": round(float(valid_vals.std()), 4),
                    "median": round(float(valid_vals.median()), 4),
                    "min": round(float(valid_vals.min()), 4),
                    "max": round(float(valid_vals.max()), 4),
                    "count": int(len(valid_vals)),
                }

    # Metriche per categoria
    if "question_category" in results_df.columns:
        for cat in results_df["question_category"].unique():
            cat_df = results_df[results_df["question_category"] == cat]
            cat_summary = {}
            for col in metric_cols:
                if col in cat_df.columns and cat_df[col].dtype in ["float64", "float32"]:
                    valid = cat_df[col].dropna()
                    if len(valid) > 0:
                        cat_summary[col] = round(float(valid.mean()), 4)
            if cat_summary:
                summary["metrics_by_category"][cat] = cat_summary

    summary_path = output_dir / "evaluation_summary.json"
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False, default=str)
    console.print(f"  Summary: {summary_path}")

    # ══════════════════════════════════════════════════════════════════════
    #  REPORT FINALE
    # ══════════════════════════════════════════════════════════════════════

    console.rule("[bold cyan]RAGAS RESULTS[/bold cyan]")

    # Tabella metriche globali
    if RICH_AVAILABLE:
        table = Table(title="Global Metrics", show_header=True)
        table.add_column("Metric", style="cyan")
        table.add_column("Mean", justify="right", style="bold green")
        table.add_column("Std", justify="right")
        table.add_column("Min", justify="right")
        table.add_column("Max", justify="right")
        table.add_column("N", justify="right")

        for name, stats in summary["metrics_summary"].items():
            table.add_row(
                name,
                f"{stats['mean']:.4f}",
                f"{stats['std']:.4f}",
                f"{stats['min']:.4f}",
                f"{stats['max']:.4f}",
                str(stats['count']),
            )
        console.print(table)
    else:
        for name, stats in summary["metrics_summary"].items():
            console.print(f"  {name:40s} → mean={stats['mean']:.4f} (±{stats['std']:.4f})")

    # Tabella metriche per categoria
    if summary["metrics_by_category"]:
        console.print("\n[bold]Metrics by Category:[/bold]")
        if RICH_AVAILABLE:
            cat_table = Table(show_header=True)
            cat_table.add_column("Category", style="cyan")
            for m in metric_names:
                cat_table.add_column(m, justify="right")
            for cat, scores in summary["metrics_by_category"].items():
                row = [cat]
                for m in metric_names:
                    col_name = metric_name_mapping.get(m, m)
                    val = scores.get(col_name)
                    row.append(f"{val:.4f}" if val is not None else "N/A")
                cat_table.add_row(*row)
            console.print(cat_table)

    # Token & Costi
    console.print(f"\n  Total time:     {total_time / 60:.1f} minuti")
    console.print(f"  LLM Calls:     {tracker.total_calls:,}")
    console.print(f"  Retry:            {tracker.retries}")
    console.print(f"  Errors:           {len(errors)}")
    console.print(f"  Input tokens:      {tracker.total_input_tokens:,}")
    console.print(f"  Output tokens:     {tracker.total_output_tokens:,}")
    console.print(f"  TOTAL tokens:     {tracker.total_tokens:,}")

    cost = tracker.cost_estimate(judge_model)
    if "total_cost_usd" in cost:
        console.print(f"\n  [bold]Estimated cost: ${cost['total_cost_usd']:.4f}[/bold]")
        console.print(f"     Input:  ${cost['input_cost_usd']:.4f}")
        console.print(f"     Output: ${cost['output_cost_usd']:.4f}")

    console.print(f"\n  Output directory: [bold]{output_dir}[/bold]")

    return summary, results_df


