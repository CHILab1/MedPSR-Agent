logger = logging.getLogger("ragas_custom_metrics")


def parse_json_response(text: str) -> dict:
    """
    Parses JSON from the model response, handling markdown blocks and falling back
    to robust regex extraction if the JSON formatting is completely broken.
    """
    cleaned_text = text.strip()
    
    # 1. Try to extract markdown JSON block
    json_match = re.search(r"```json\s*(.*?)\s*```", cleaned_text, re.DOTALL)
    if json_match:
        try:
            return json.loads(json_match.group(1))
        except json.JSONDecodeError:
            pass

    # 2. Try to extract anything enclosed in curly braces
    brace_match = re.search(r"(\{.*\})", cleaned_text, re.DOTALL)
    if brace_match:
        try:
            return json.loads(brace_match.group(1))
        except json.JSONDecodeError:
            pass

    # 3. Try to parse the entire text as JSON
    try:
        return json.loads(cleaned_text)
    except json.JSONDecodeError:
        pass

    # 4. Smart Fallback: search for explicit score keywords (e.g., "score: 0.75", "punteggio = 1.0")
    keyword_match = re.search(r'(?:score|punteggio|score":|punteggio":)\s*[:=]?\s*(0\.\d+|1\.0|0\.0|[01])', cleaned_text, re.IGNORECASE)
    if keyword_match:
        extracted_score = float(keyword_match.group(1))
        logger.warning(
            f"Malformed JSON. Extracted score via keyword regex: {extracted_score}. "
            f"Original response: {cleaned_text}"
        )
        return {
            "score": extracted_score,
            "reasoning": "Fallback: JSON parsing failed, score extracted via keyword regex."
        }

    # 5. Search for an isolated decimal float (e.g., 0.75) which is highly likely the score
    decimal_match = re.search(r'\b(0\.\d+|1\.0|0\.0)\b', cleaned_text)
    if decimal_match:
        extracted_score = float(decimal_match.group(1))
        logger.warning(
            f"Malformed JSON. Extracted isolated decimal float: {extracted_score}. "
            f"Original response: {cleaned_text}"
        )
        return {
            "score": extracted_score,
            "reasoning": "Fallback: JSON parsing failed, isolated decimal float extracted."
        }

    # 6. Search for isolated binary values (0 or 1)
    binary_match = re.search(r'\b([01])\b', cleaned_text)
    if binary_match:
        extracted_score = float(binary_match.group(1))
        logger.warning(
            f"Malformed JSON. Extracted isolated binary score: {extracted_score}. "
            f"Original response: {cleaned_text}"
        )
        return {
            "score": extracted_score,
            "reasoning": "Fallback: JSON parsing failed, isolated binary score extracted."
        }

    raise ValueError(f"Unable to parse score or JSON from LLM response: {cleaned_text}")


@dataclass
class ClinicalComprehensiveness(SingleTurnMetric):
    """
    A custom RAGAS metric that evaluates whether the final report has comprehensively captured
    the pharmacological and diagnostic patterns present in the provided patient context.
    Utilizes Chain-of-Thought (reasoning) and an explicit rubric to guarantee objective scoring.
    """
    name: str = "clinical_comprehensiveness"
    _required_columns: t.Dict[MetricType, t.Set[str]] = field(
        default_factory=lambda: {MetricType.SINGLE_TURN: {"user_input", "response", "retrieved_contexts"}}
    )
    llm: t.Any = None

    def __post_init__(self):
        self.name = "clinical_comprehensiveness"

    def init(self, run_config: RunConfig) -> None:
        pass

    async def _single_turn_ascore(self, sample: SingleTurnSample, callbacks: Callbacks) -> float:
        question = sample.user_input
        response = sample.response
        contexts = "\n".join(sample.retrieved_contexts)

        prompt = f"""You are an expert clinical AI evaluator.
Your task is to evaluate whether the clinical report generated by an AI synthesizer comprehensively captures the important pharmacological and diagnostic patterns present in the provided PATIENT CONTEXT.
In particular, pay close attention to whether the synthesizer ignored information from cases at the end of the context (the "Lost in the middle" problem).

Score the response on a continuous scale from 0.0 to 1.0 based on the following rubric:
- 1.0: All key pharmacological treatments and diagnostic findings from all parts of the context (beginning, middle, and end) are comprehensively captured and integrated.
- 0.75: Almost all critical patterns are captured, with only minor, non-essential details missing.
- 0.50: Moderate omissions (e.g., a patient case or a major drug class was ignored, or the latter portion of the context was neglected).
- 0.25: Significant omissions; major parts of the patient context were completely ignored.
- 0.00: The report completely misses the patterns or ignores the patient context entirely.

PATIENT CONTEXT:
{contexts}

QUESTION:
{question}

RESPONSE:
{response}

You MUST respond strictly in the following JSON format:
{{
  "reasoning": "A step-by-step clinical analysis checking the beginning, middle, and end of the patient context against the response to identify what was captured and what was omitted.",
  "score": <float between 0.0 and 1.0>
}}
"""
        try:
            res = await self.llm.agenerate_text(prompt=prompt)
            text = res.generations[0][0].text.strip()
            parsed = parse_json_response(text)
            score = float(parsed.get("score", 0.0))
            return max(0.0, min(1.0, score))
        except Exception as e:
            logger.error(f"Error in ClinicalComprehensiveness: {e}")
            return 0.0


