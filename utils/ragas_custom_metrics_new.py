@dataclass
class ContradictionRate(SingleTurnMetric):
    """
    A custom RAGAS metric that evaluates if there are contradictions between the specialist LLM reports
    (provided in the reference field) and the final synthesizer report (response).
    A HIGHER value means MORE contradictions (1.0 = completely contradictory).
    Utilizes Chain-of-Thought (reasoning) and an explicit rubric to guarantee objective scoring.
    """
    name: str = "contradiction_rate"
    _required_columns: t.Dict[MetricType, t.Set[str]] = field(
        default_factory=lambda: {MetricType.SINGLE_TURN: {"response", "reference"}}
    )
    llm: t.Any = None

    def __post_init__(self):
        self.name = "contradiction_rate"

    def init(self, run_config: RunConfig) -> None:
        pass

    async def _single_turn_ascore(self, sample: SingleTurnSample, callbacks: Callbacks) -> float:
        final_report = sample.response
        specialist_reports = sample.reference
        
        # If there are no specialist reports to contradict, rate is 0.0
        if not specialist_reports or len(specialist_reports.strip()) == 0:
            return 0.0

        prompt = f"""You are an expert clinical AI evaluator.
You will be provided with intermediate reports generated by multiple AI specialists, and a FINAL synthesized report.
Your task is to determine the CONTRADICTION RATE: are there medical contradictions, hallucinated changes, or significant discrepancies between what the specialists said and what the final synthesizer wrote?

Score from 0.0 to 1.0 based on the following rubric:
- 1.0: The final report completely contradicts the specialists (e.g., inverting diagnoses, swapping drug names) or introduces major hallucinated clinical claims not present in the specialists' reports.
- 0.75: Major discrepancies or several clear contradictions exist between the reports.
- 0.50: Moderate discrepancies or a single significant contradiction exists.
- 0.25: Very minor discrepancies (e.g., slight difference in wording that doesn't change medical meaning).
- 0.00: Absolutely no contradictions or discrepancies. The final report faithfully synthesizes the specialists without altering their medical meaning.

SPECIALIST REPORTS:
{specialist_reports}

FINAL SYNTHESIZED REPORT:
{final_report}

You MUST respond strictly in the following JSON format:
{{
  "reasoning": "A step-by-step comparison between the specialist reports and the final report, identifying any contradictions or hallucinated information.",
  "score": <float between 0.0 and 1.0>
}}
"""
        try:
            res = await self.llm.agenerate_text(prompt=prompt)
            text = res.generations[0][0].text.strip()
            parsed = parse_json_response(text)
            score = float(parsed.get("score", 0.0))
            return max(0.0, min(1.0, score))
        except Exception as e:
            logger.error(f"Error in ContradictionRate: {e}")
            return 0.0
